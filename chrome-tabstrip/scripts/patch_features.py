#!/usr/bin/env python3
"""Descrive le funzioni facoltative della patch incluse in un build (e quelle mancanti).

Uso:
  patch_features.py kotlin <series> <patch-applicate>   file Kotlin per Firefox (GeneratedPatchFeatures.kt)
  patch_features.py json <series> <patch-applicate>     JSON per update.json e per le Release (vedi ci-update-info.sh)

<series> è patches/series; <patch-applicate> il file con le patch applicate al checkout, una per riga.
Una funzione facoltativa è "inclusa" se la sua patch è applicata, "mancante" altrimenti.
"""

import json
import re
import sys

KOTLIN_HEADER = """\
/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

// Generated by chrome-tabstrip/scripts/apply.sh from the patches applied to this checkout: don't edit it, and don't
// include it in a patch.

package org.mozilla.fenix.patchfeatures

"""


def read_series(path):
    features = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            fields = [field.strip() for field in line.split("|")]
            if len(fields) != 4:
                sys.exit(f"{path}: riga non valida (servono 4 campi separati da |): {line}")
            file, kind, name_it, name_en = fields
            features.append(
                {
                    "file": file,
                    "optional": kind == "facoltativa",
                    "id": re.sub(r"^\d{4}-", "", file[: -len(".patch")] if file.endswith(".patch") else file),
                    "name": {"it": name_it, "en": name_en},
                }
            )
    return features


def read_applied(path):
    with open(path, encoding="utf-8") as f:
        return {line.strip() for line in f if line.strip()}


def split_features(series_path, applied_path):
    applied = read_applied(applied_path)
    optional = [feature for feature in read_series(series_path) if feature["optional"]]
    included = [feature for feature in optional if feature["file"] in applied]
    missing = [feature for feature in optional if feature["file"] not in applied]
    return included, missing


def kotlin_class_name(feature_id):
    """tab-groups -> TabGroupsFeature: the object each optional patch must define."""
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", feature_id) if part) + "Feature"


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def kotlin_feature(feature):
    names = ", ".join(f"{kotlin_string(lang)} to {kotlin_string(name)}" for lang, name in feature["name"].items())
    return f"PatchFeature(id = {kotlin_string(feature['id'])}, names = mapOf({names}))"


def kotlin_list(items, indent="            "):
    if not items:
        return "emptyList()"
    return "listOf(\n" + "".join(f"{indent}{item},\n" for item in items) + indent[:-4] + ")"


def to_kotlin(included, missing):
    return (
        KOTLIN_HEADER
        + "/** The optional features of the patch included in this build, the missing ones and their entry points. */\n"
        + "internal object GeneratedPatchFeatures {\n"
        + f"    val included: List<PatchFeature> =\n        {kotlin_list([kotlin_feature(f) for f in included])}\n\n"
        + f"    val missing: List<PatchFeature> =\n        {kotlin_list([kotlin_feature(f) for f in missing])}\n\n"
        + "    val hooks: List<PatchFeatureHooks> =\n"
        + f"        {kotlin_list([kotlin_class_name(f['id']) for f in included])}\n"
        + "}\n"
    )


def to_json(included, missing):
    def describe(feature):
        return {"id": feature["id"], "name": feature["name"]}

    return json.dumps(
        {"features": [describe(f) for f in included], "missingFeatures": [describe(f) for f in missing]},
        ensure_ascii=False,
        indent=2,
    )


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ("kotlin", "json"):
        sys.exit(__doc__)
    included, missing = split_features(sys.argv[2], sys.argv[3])
    print(to_kotlin(included, missing) if sys.argv[1] == "kotlin" else to_json(included, missing), end="")
    if sys.argv[1] == "json":
        print()


if __name__ == "__main__":
    main()
